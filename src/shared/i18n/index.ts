export type I18nKey = keyof typeof messages.en;

let currentLanguage: UiLanguage = readInitialLanguage();
const listeners = new Set<() => void>();

function normalizeSupportedLanguage(language: string | undefined): UiLanguage | null {
  const normalized = language?.trim().toLowerCase();
  if (normalized === 'zh' || normalized?.startsWith('zh-')) return 'zh';
  if (normalized === 'en' || normalized?.startsWith('en-')) return 'en';
  return null;
}

function readStoredLanguage(): UiLanguage | null {
  if (typeof window === 'undefined') return null;
  try {
    const current = normalizeSupportedLanguage(
      window.localStorage.getItem(STORAGE_KEY) ?? undefined
    );
    if (current) {
      window.localStorage.removeItem(LEGACY_STORAGE_KEY);
      return current;
    }
    const legacy = normalizeSupportedLanguage(
      window.localStorage.getItem(LEGACY_STORAGE_KEY) ?? undefined
    );
    if (!legacy) return null;
    window.localStorage.setItem(STORAGE_KEY, legacy);
    if (window.localStorage.getItem(STORAGE_KEY) === legacy) {
      window.localStorage.removeItem(LEGACY_STORAGE_KEY);
    }
    return legacy;
  } catch {
    return null;
  }
}

function readPreferredLanguages(): readonly string[] {
  if (typeof navigator === 'undefined') return [];
  try {
    return navigator.languages.length
      ? navigator.languages
      : navigator.language
        ? [navigator.language]
        : [];
  } catch {
    return [];
  }
}

function readInitialLanguage(): UiLanguage {
  const stored = readStoredLanguage();
  if (stored) return stored;
  for (const preferred of readPreferredLanguages()) {
    const supported = normalizeSupportedLanguage(preferred);
    if (supported) return supported;
  }
  return 'en';
}

function syncDocumentLanguage(language: UiLanguage) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  }
}

syncDocumentLanguage(currentLanguage);

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

function getSnapshot() {
  return currentLanguage;
}

export function setUiLanguage(language: UiLanguage) {
  currentLanguage = language;
  syncDocumentLanguage(language);
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
      if (window.localStorage.getItem(STORAGE_KEY) === language) {
        window.localStorage.removeItem(LEGACY_STORAGE_KEY);
      }
    } catch {
      // Keep the in-memory preference when browser storage is unavailable.
    }
  }
  listeners.forEach((listener) => listener());
}

function toggleUiLanguage() {
  setUiLanguage(currentLanguage === 'en' ? 'zh' : 'en');
}

function translate(
  key: I18nKey,
  params: Record<string, string | number> = {},
  language = currentLanguage
) {
  let value: string = messages[language][key] ?? messages.en[key] ?? key;
  for (const [paramKey, paramValue] of Object.entries(params)) {
    value = value.replaceAll(`{${paramKey}}`, String(paramValue));
  }
  return value;
}

export function useUiI18n() {
  const language = useSyncExternalStore(subscribe, getSnapshot, getSnapshot);
  return {
    language,
    setLanguage: setUiLanguage,
    toggleLanguage: toggleUiLanguage,
    t: (key: I18nKey, params?: Record<string, string | number>) => translate(key, params, language),
  };
}
