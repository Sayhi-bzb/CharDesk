import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const revision = "c58ea3637f3968e0e6e79cd92cf9aace7ef89ee2";
const sourceUrl = `https://raw.githubusercontent.com/xtermjs/xterm.js/${revision}/addons/addon-webgl/src/customGlyphs/CustomGlyphDefinitions.ts`;
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const output = resolve(root, "packages/rendering/src/cell-graphics-upstream.ts");

const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`Unable to fetch xterm.js definitions: ${response.status}`);
const source = await response.text();
const importPattern = /import \{[^\n]+\} from '\.\/Types';/;
if (!importPattern.test(source)) throw new Error("Upstream Types import was not found.");
const gitBranchPartNames = [
  "LINE_H", "LINE_V", "FADE_RIGHT", "FADE_LEFT", "FADE_DOWN", "FADE_UP",
  "CURVE_DOWN_RIGHT", "CURVE_DOWN_LEFT", "CURVE_UP_RIGHT", "CURVE_UP_LEFT",
  "NODE_FILL", "NODE_STROKE", "NODE_LINE_RIGHT", "NODE_LINE_LEFT", "NODE_LINE_DOWN", "NODE_LINE_UP",
];
const generatedNotice = `// Generated by scripts/rendering/sync-xterm-cell-graphics.mjs\n// Source revision: ${revision}\n/* eslint-disable @typescript-eslint/no-unused-vars -- pinned upstream signatures */\n\n`;
const adapted = generatedNotice + source.replace(
  importPattern,
  `import { CustomGlyphDefinitionType, CustomGlyphScaleType, CustomGlyphVectorType, type CustomGlyphCharacterDefinition, type CustomGlyphDefinitionPart, type CustomGlyphPathDrawFunctionDefinition } from "./cell-graphics-types.js";`
).replace(
  "type: CustomGlyphDefinitionType.PATH_FUNCTION, data: CustomGlyphPathDrawFunctionDefinition",
  "type: typeof CustomGlyphDefinitionType.PATH_FUNCTION, data: CustomGlyphPathDrawFunctionDefinition"
).replace(
  /\nexport const blockPatternCodepoints = new Set<number>\(\[[\s\S]*?\n\]\);\n/,
  "\n"
).replace(
  "const rowH = [3 / 8, 2 / 8, 3 / 8];",
  "const rowH = [3 / 8, 2 / 8, 3 / 8] as const;"
).replace(
  "const rowY = [0, 3 / 8, 5 / 8];",
  "const rowY = [0, 3 / 8, 5 / 8] as const;"
).replace(
  /const enum Shapes \{([\s\S]*?)\n\}/,
  (_match, body) => `const Shapes = {${body.replace(/^(\s*\/\*\*.*?\*\/\s*)([A-Z_]+) =/gm, "$1$2:")}\n} as const;`
).replace(
  /namespace GitBranchSymbolsParts \{([\s\S]*?)\n\}\n\nexport const customGlyphDefinitions/,
  (_match, body) => `const GitBranchSymbolsParts = (() => {${body.replaceAll("export const ", "const ")}\n  return { ${gitBranchPartNames.join(", ")} };\n})();\n\nexport const customGlyphDefinitions`
).replaceAll(
  "rowY[row]",
  "rowYValue"
).replaceAll(
  "rowH[row]",
  "rowHeight"
).replace(
  "const rightBit = (pattern >> (row * 2 + 1)) & 1;",
  "const rightBit = (pattern >> (row * 2 + 1)) & 1;\n        const rowYValue = rowY[row]!;\n        const rowHeight = rowH[row]!;"
).replace(
  /\bxp\b/g,
  "_xp"
).replace(
  /\byp\b/g,
  "_yp"
);
await mkdir(dirname(output), { recursive: true });
await writeFile(output, adapted);
console.log(`Pinned xterm.js Cell graphics ${revision} -> ${output}`);
